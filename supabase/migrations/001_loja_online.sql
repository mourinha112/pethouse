comment on column public.products.visivel_loja     is 'aparece no catálogo da loja online';
comment on column public.products.vende_fracionado is 'aceita venda por kg na loja online';

-- Preenche a partir do campo "tipo" que o PDV já usa (só onde está vazio)
update public.products set especie = tipo
  where especie is null and tipo in ('cao', 'gato');

update public.products set perfil = tipo
  where perfil is null and tipo in ('filhote', 'castrado');

-- Produto que não é ração não se vende fracionado
update public.products set vende_fracionado = false
  where categoria is not null and categoria <> 'racao';

-- ---------------------------------------------------------------------
-- 2. Pedidos da loja online
-- ---------------------------------------------------------------------
create table if not exists public.orders (
  id               bigint generated by default as identity primary key,
  client_id        bigint references public.clients(id) on delete set null,
  cliente_nome     text        not null,
  cliente_whatsapp text        not null,
  tipo_entrega     text        not null default 'entrega',  -- entrega | retirada
  endereco         text,
  referencia       text,
  janela           text,                                    -- "Hoje, 14h-17h"
  observacao       text,
  subtotal         numeric(10,2) not null default 0,
  frete            numeric(10,2) not null default 0,
  total            numeric(10,2) not null default 0,
  status           text        not null default 'novo',     -- novo | confirmado | separando | pronto | entregue | cancelado
  assinatura       boolean     not null default false,
  frequencia       text,                                    -- semanal | quinzenal | mensal
  sale_id          bigint references public.sales(id) on delete set null,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);

-- quantidade_kg segue exatamente a mesma convenção de sale_items do PDV:
--   tipo_venda = 'kg'      -> quilos
--   tipo_venda = 'saco'    -> número de sacos fechados
--   tipo_venda = 'unidade' -> número de unidades
create table if not exists public.order_items (
  id             bigint generated by default as identity primary key,
  order_id       bigint not null references public.orders(id) on delete cascade,
  product_id     bigint references public.products(id) on delete set null,
  descricao      text   not null,
  tipo_venda     text   not null default 'kg',
  quantidade_kg  numeric(10,3) not null default 0,
  preco_unitario numeric(10,4) not null default 0,
  subtotal       numeric(10,2) not null default 0
);

create index if not exists orders_status_idx     on public.orders (status);
create index if not exists orders_created_at_idx on public.orders (created_at desc);
create index if not exists orders_whatsapp_idx   on public.orders (cliente_whatsapp);
create index if not exists order_items_order_idx on public.order_items (order_id);

