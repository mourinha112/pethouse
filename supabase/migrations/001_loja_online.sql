-- ---------------------------------------------------------------------
-- 4. Acesso
--
-- Mantém a mesma postura das outras tabelas do projeto: a chave anon
-- (que já está no front e na API) consegue ler e gravar pedidos.
--
-- COMO FECHAR DEPOIS (recomendado quando sobrar tempo): crie a variável
-- SUPABASE_SERVICE_ROLE_KEY na Vercel, faça a API usá-la, e troque as
-- policies abaixo por apenas o INSERT do anon. Aí só o servidor lê
-- pedidos, e ninguém com a chave pública consegue listar os seus.
-- ---------------------------------------------------------------------
alter table public.orders      enable row level security;
alter table public.order_items enable row level security;

drop policy if exists loja_orders_all      on public.orders;
drop policy if exists loja_order_items_all on public.order_items;

create policy loja_orders_all on public.orders
  for all to anon, authenticated using (true) with check (true);

create policy loja_order_items_all on public.order_items
  for all to anon, authenticated using (true) with check (true);
